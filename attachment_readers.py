def _extension(filename: str) -> str:
    _, dot, ext = filename.rpartition(".")
    return f".{ext.lower()}" if dot else ""


def supported_extensions() -> list:
    return sorted(_READERS)


def is_supported(filename: str, mime_type: str = "") -> bool:
    """Whether extract_text can read this file, judged from its name alone.

    Needed before the bytes exist: read_email lists what is attached without
    downloading anything, and has to say which ones are worth asking for."""
    ext = _extension(filename)
    if ext in _READERS:
        return True
    if not ext and mime_type:
        return mime_type.startswith("text/") or mime_type == "application/pdf"
    return False


def _resolve_reader(filename: str, mime_type: str):
    """Returns (reader, error). Exactly one of the two is None."""
    ext = _extension(filename)
    reader = _READERS.get(ext)

    if reader is None and not ext and mime_type:
        # No extension to go on - fall back to the declared type, which is the
        # only remaining signal.
        if mime_type.startswith("text/"):
            reader = _rows_plain_text
        elif mime_type == "application/pdf":
            reader = _rows_pdf

    if reader is not None:
        return reader, None
    if ext in _KNOWN_UNSUPPORTED:
        return None, f"❌ {_KNOWN_UNSUPPORTED[ext]}"
    return None, (
        f"❌ סוג הקובץ {ext or mime_type or 'לא ידוע'} אינו נתמך לקריאה. "
        f"נתמכים: {', '.join(supported_extensions())}"
    )


def _size_error(raw: bytes):
    if not raw:
        return "❌ הקובץ ריק."
    if len(raw) > MAX_ATTACHMENT_BYTES:
        size_mb = len(raw) / (1024 * 1024)
        return (
            f"❌ הקובץ גדול מדי לקריאה ({size_mb:.1f}MB, המגבלה "
            f"{MAX_ATTACHMENT_BYTES // (1024 * 1024)}MB)."
        )
    return None


def iter_rows(filename: str, raw: bytes, mime_type: str = ""):
    """Streams the file as (section, row_number, text) with no limit on length.

    Search runs on this, so scanning is bounded by the file, not by a cap: the
    whole workbook is examined however many rows it has. Nothing is accumulated,
    which is what keeps a large file from exhausting the worker's memory."""
    reader, error = _resolve_reader(filename, mime_type)
    if reader is None:
        raise ValueError(error)
    return reader(raw)


def extract_text(filename: str, raw: bytes, mime_type: str = "", part: int = 1) -> str:
    """Converts one attachment's bytes to text, or explains why it cannot.

    Long files come back in numbered parts rather than cut off: pass part=2 for
    the next slice. Always returns a string - callers surface it to the user
    as-is, so a failure has to read as an explanation rather than as a stack
    trace or as silence."""
    error = _size_error(raw)
    if error:
        return error
    reader, error = _resolve_reader(filename, mime_type)
    if reader is None:
        return error

    try:
        chunks, section, length, capped = [], None, 0, False
        for row_section, _, row in reader(raw):
            if row_section != section:
                section = row_section
                if section:
                    heading = f"\n--- {section} ---"
                    chunks.append(heading)
                    length += len(heading) + 1
            chunks.append(row)
            length += len(row) + 1
            if length > MAX_EXTRACT_CHARS:
                capped = True
                break
        text = "\n".join(chunks)
    except zipfile.BadZipFile:
        # xlsx and docx are both zip containers; a corrupted or mislabelled file
        # fails here rather than anywhere more informative.
        return "❌ הקובץ פגום או שסיומת הקובץ לא תואמת לתוכן שלו."
    except Exception as e:
        logger.error(f"Attachment parse failed for {filename!r}: {e}")
        return f"❌ לא הצלחתי לפענח את הקובץ: {e}"

    if not text.strip():
        if reader is _rows_pdf:
            # A scanned document is an image inside a PDF wrapper. Saying "empty"
            # would be misleading - there is content, it just is not text.
            return (
                "ה-PDF לא מכיל טקסט שניתן לחלץ. סביר שזה מסמך סרוק (תמונה), "
                "וקריאה שלו תדרוש OCR שלא מותקן כאן."
            )
        return "הקובץ נקרא בהצלחה אך אין בו טקסט."

    paged = _page(text, part)
    if capped:
        paged += (
            "\n[הקובץ ארוך במיוחד ולא נטען כולו לזיכרון. "
            "כדי למצוא שורות מסוימות עדיף לחפש בו לפי מילות מפתח - החיפוש סורק הכול.]"
        )
    return paged


# --- Searching inside an attachment -------------------------------------------
#
# Reading a whole file into the prompt is the wrong tool for "which rows mention
# Ramla and me": it costs the whole file in tokens and still gets paged. Search
# streams every row, matches in Python, and returns only the hits - so the scan
# has no ceiling at all while the answer stays small.

# Hebrew makes naive substring matching wrong in both directions. Spelling is not
# stable across writers - כתיב מלא vs חסר turns קריית into קרית - and abbreviations
# carry gershayim that may be the Hebrew mark or an ASCII quote. Normalising both
# sides collapses those differences instead of requiring the file to be tidy.
_HEBREW_MARKS = str.maketrans({
    "׳": "", "״": "", "'": "", '"': "", "’": "", "“": "", "”": "",
    "־": " ", "-": " ", "_": " ", "/": " ", "\\": " ", ",": " ", ".": " ",
    "(": " ", ")": " ", "[": " ", "]": " ", ":": " ", ";": " ", "|": " ",
})
_FINAL_LETTERS = str.maketrans({"ך": "כ", "ם": "מ", "ן": "נ", "ף": "פ", "ץ": "צ"})


def _normalise(text: str) -> str:
    text = text.lower().translate(_HEBREW_MARKS).translate(_FINAL_LETTERS)
    # Niqqud and cantillation carry no meaning for a name match and would only
    # break equality between two spellings of the same word.
    text = "".join(c for c in text if not "֑" <= c <= "ׇ")
    # כתיב מלא vs חסר: קריית -> קרית, ראשון -> ראשנ? no - only doubled letters.
    while "יי" in text:
        text = text.replace("יי", "י")
    while "וו" in text:
        text = text.replace("וו", "ו")
    return " ".join(text.split())


def _tokens(text: str) -> list:
    return _normalise(text).split()


# Itai's territory, as he listed it. Each entry maps one city to the spellings a
# real file actually uses - Hebrew full and defective, the common abbreviation,
# and the English transliterations, which vary by whoever typed the export.
CITY_ALIASES = {
    "ראשון לציון": ["ראשון לציון", "ראשל צ", "רשל צ", "ראשלצ", "רשלצ",
                    "rishon lezion", "rishon letzion", "rishon le zion", "rishon"],
    "רמלה": ["רמלה", "ramla", "ramle", "ramleh"],
    "לוד": ["לוד", "lod", "lydda"],
    "קריית אונו": ["קריית אונו", "קרית אונו", "kiryat ono", "qiryat ono", "kyriat ono"],
    "קריית עקרון": ["קריית עקרון", "קרית עקרון", "kiryat ekron", "kiryat akron",
                    "qiryat eqron", "kiryat ackron"],
    "יבנה": ["יבנה", "yavne", "yavneh", "javne"],
    "אור יהודה": ["אור יהודה", "or yehuda", "or yehuda", "or yehudah"],
}


def expand_keyword(keyword: str) -> list:
    """Returns every spelling worth trying for one search term.

    A city the user names in Hebrew has to match its English column too, and vice
    versa, because a single export mixes both."""
    normalised = _normalise(keyword)
    if not normalised:
        return []
    for city, aliases in CITY_ALIASES.items():
        for alias in aliases:
            if _normalise(alias) == normalised:
                return [_normalise(a) for a in aliases if _normalise(a)]
    return [normalised]


def _matches(row_tokens: list, needle_tokens: list) -> bool:
    """True when the needle appears as a run of whole tokens in the row.

    Whole tokens rather than a substring: 'לוד' is three letters and would
    otherwise match inside unrelated words, and 'Lod' would match 'Lodging'.
    Running over tokens also makes a two-word city like 'אור יהודה' match even
    when the cell wraps it in other text."""
    if not needle_tokens:
        return False
    span = len(needle_tokens)
    return any(
        row_tokens[i:i + span] == needle_tokens
        for i in range(len(row_tokens) - span + 1)
    )


def _split_terms(raw) -> list:
    if raw is None:
        return []
    if isinstance(raw, (list, tuple)):
        items = list(raw)
    else:
        # The model sends one string; commas and newlines are how a person lists
        # things, so both separate terms.
        items = str(raw).replace("\n", ",").split(",")
    return [t.strip() for t in items if str(t).strip()]


def _group(terms: list) -> list:
    """One search group: a list of alternative token-lists, any of which matches."""
    expanded = []
    for term in terms:
        for spelling in expand_keyword(term):
            tokens = spelling.split()
            if tokens and tokens not in expanded:
                expanded.append(tokens)
    return expanded


def search(filename: str, raw: bytes, keywords, must_also_match=None,
           mime_type: str = "") -> str:
    """Scans every row of the file and returns the ones that match.

    keywords match on OR. must_also_match is a second OR group ANDed with the
    first, which is what "Ramla or Lod, but only my rows or Nikita's" needs -
    two independent lists rather than one flat list of terms.
    """
    error = _size_error(raw)
    if error:
        return error

    primary = _group(_split_terms(keywords))
    if not primary:
        return "❌ לא נמסרו מילות חיפוש."
    secondary = _group(_split_terms(must_also_match))

    try:
        rows = iter_rows(filename, raw, mime_type)
    except ValueError as e:
        return str(e)

    matches, scanned, truncated = [], 0, False
    try:
        for section, number, row in rows:
            scanned += 1
            tokens = _tokens(row)
            if not any(_matches(tokens, n) for n in primary):
                continue
            if secondary and not any(_matches(tokens, n) for n in secondary):
                continue
            if len(matches) >= MAX_MATCHES_RETURNED:
                truncated = True
                # Keep scanning: the total is worth reporting accurately even
                # when not every hit can be shown.
                continue
            matches.append((section, number, row))
    except zipfile.BadZipFile:
        return "❌ הקובץ פגום או שסיומת הקובץ לא תואמת לתוכן שלו."
    except Exception as e:
        logger.error(f"Attachment search failed for {filename!r}: {e}")
        return f"❌ לא הצלחתי לפענח את הקובץ: {e}"

    terms_text = ", ".join(_split_terms(keywords))
    also_text = ", ".join(_split_terms(must_also_match))
    criteria = f"'{terms_text}'" + (f" יחד עם '{also_text}'" if also_text else "")

    if not matches:
        return (
            f"סרקתי את כל הקובץ {filename} ({scanned:,} שורות) ולא נמצאה אף שורה "
            f"שמתאימה ל-{criteria}."
        )

    lines, section = [], None
    for row_section, number, row in matches:
        if row_section != section:
            section = row_section
            if section:
                lines.append(f"--- {section} ---")
        lines.append(f"{number}: {row}")
    body = "\n".join(lines)
    if len(body) > MAX_SEARCH_OUTPUT_CHARS:
        body = body[:MAX_SEARCH_OUTPUT_CHARS] + "\n[...]"
        truncated = True

    total = len(matches) + (1 if truncated else 0)
    header = (
        f"🔎 חיפוש ב-{filename}: נסרקו כל {scanned:,} השורות, "
        f"נמצאו {len(matches)} שורות שמתאימות ל-{criteria}."
    )
    if truncated:
        header += f" (מוצגות הראשונות; יש עוד - כדאי לצמצם את החיפוש.)"
    return f"{header}\n\n{body}"
