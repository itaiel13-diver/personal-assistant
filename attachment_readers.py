"""Turning an attachment's bytes into text a language model can actually read.

Deliberately separate from gmail_tools: nothing here knows about Gmail, mailboxes
or tokens, which keeps every converter a pure bytes -> str function that can be
tested against a file built in the test itself.

Dispatch is on the FILENAME EXTENSION, not the MIME type. Mail clients are
careless about Content-Type - a spreadsheet forwarded through a phone routinely
arrives as application/octet-stream - so the extension is the more reliable
signal in practice. The MIME type is only a fallback when there is no extension.
"""

import csv
import io
import logging
import zipfile

logger = logging.getLogger(__name__)

# The worker on Render's free tier has limited memory, and every converter below
# holds the whole file plus its parsed form at once. Refuse early and clearly
# rather than being killed mid-parse, which looks to the user like a silent hang.
MAX_ATTACHMENT_BYTES = 5 * 1024 * 1024

# One page of a plain read. The extracted text is injected into the Gemini prompt
# and costs money and context on every later message, so a whole spreadsheet
# cannot go in at once - but nothing is unreachable either: read_email_attachment
# takes a part number and iter_rows/search below scan the file with no cap at all.
MAX_TEXT_CHARS = 15000

# Extraction assembles the whole file in memory before paging it. Render's free
# worker has ~512MB and is killed silently when it runs out, which reads to the
# user as a hang rather than as an error - so the assembly stops here. Search
# does not go through this path; it streams and never holds the file.
MAX_EXTRACT_CHARS = 2_000_000

# Every row of every sheet is scanned. These bound only how much is echoed back.
MAX_MATCHES_RETURNED = 300
MAX_SEARCH_OUTPUT_CHARS = 12000


def _page(text: str, part: int) -> str:
    """Splits a long extraction into numbered pages on line boundaries.

    Paging rather than truncating: the previous version cut the file off and
    offered no way to ask for the rest, so data past the cut was simply
    unreachable however the question was phrased."""
    text = text.strip()
    if len(text) <= MAX_TEXT_CHARS:
        return text

    pages, current = [], ""
    for line in text.split("\n"):
        # A single line longer than a page is split mid-line - rare, and better
        # than emitting a page that busts the budget.
        while len(line) > MAX_TEXT_CHARS:
            if current:
                pages.append(current)
                current = ""
            pages.append(line[:MAX_TEXT_CHARS])
            line = line[MAX_TEXT_CHARS:]
        if len(current) + len(line) + 1 > MAX_TEXT_CHARS:
            pages.append(current)
            current = line
        else:
            current = f"{current}\n{line}" if current else line
    if current:
        pages.append(current)

    total = len(pages)
    index = max(1, min(part, total))
    header = f"[חלק {index} מתוך {total}]"
    if index < total:
        footer = (
            f"\n\n[סוף חלק {index}. יש עוד {total - index} חלקים - "
            f"אפשר לבקש את חלק {index + 1}.]"
        )
    else:
        footer = f"\n\n[זה החלק האחרון ({total} מתוך {total}). הקובץ נקרא במלואו.]"
    return f"{header}\n{pages[index - 1]}{footer}"


def _decode(raw: bytes) -> str:
    """Hebrew mail attachments are usually UTF-8 but Windows-authored CSVs are
    often cp1255, and a wrong guess yields mojibake rather than an error."""
    for encoding in ("utf-8-sig", "utf-8", "cp1255", "iso-8859-8"):
        try:
            return raw.decode(encoding)
        except UnicodeDecodeError:
            continue
    return raw.decode("utf-8", errors="replace")


def _cells_to_row(values) -> str:
    cells = ["" if v is None else str(v).strip() for v in values]
    return " | ".join(cells) if any(cells) else ""


def _rows_plain_text(raw: bytes):
    for number, line in enumerate(_decode(raw).splitlines(), start=1):
        if line.strip():
            yield "", number, line.strip()


def _rows_delimited(raw: bytes):
    text = _decode(raw)
    # Sniffing beats assuming a comma: exports from Hebrew Excel are frequently
    # semicolon-separated, which would otherwise come out as one column.
    sample = text[:4000]
    try:
        delimiter = csv.Sniffer().sniff(sample, delimiters=",;\t|").delimiter
    except csv.Error:
        delimiter = ","
    for number, values in enumerate(csv.reader(io.StringIO(text), delimiter=delimiter), start=1):
        row = _cells_to_row(values)
        if row:
            yield "", number, row


def _rows_xlsx(raw: bytes):
    from openpyxl import load_workbook

    # read_only streams the sheet instead of building the whole object graph,
    # which is what lets a large workbook be scanned end to end on a small worker.
    #
    # data_only=True returns the values Excel cached, not the formulas. A file
    # generated by a script and never opened in Excel has no cached values, so
    # formula cells come back empty - that is a property of the file, not a bug.
    workbook = load_workbook(io.BytesIO(raw), read_only=True, data_only=True)
    try:
        for sheet in workbook.worksheets:
            for number, values in enumerate(sheet.iter_rows(values_only=True), start=1):
                row = _cells_to_row(values)
                if row:
                    yield sheet.title, number, row
    finally:
        workbook.close()


def _rows_docx(raw: bytes):
    import docx

    document = docx.Document(io.BytesIO(raw))
    number = 0
    for paragraph in document.paragraphs:
        if paragraph.text.strip():
            number += 1
            yield "", number, paragraph.text.strip()
    # Tables are a separate tree in the docx model; a document whose content is
    # mostly a table would otherwise come back almost empty.
    for table in document.tables:
        for row in table.rows:
            line = _cells_to_row([c.text for c in row.cells])
            if line:
                number += 1
                yield "", number, line


def _rows_pdf(raw: bytes):
    from pypdf import PdfReader

    reader = PdfReader(io.BytesIO(raw))
    for page_number, page in enumerate(reader.pages, start=1):
        text = (page.extract_text() or "").strip()
        if not text:
            continue
        for line_number, line in enumerate(text.splitlines(), start=1):
            if line.strip():
                yield f"עמוד {page_number}", line_number, line.strip()


_READERS = {
    ".txt": _rows_plain_text, ".md": _rows_plain_text, ".json": _rows_plain_text,
    ".log": _rows_plain_text, ".xml": _rows_plain_text, ".html": _rows_plain_text,
    ".csv": _rows_delimited, ".tsv": _rows_delimited,
    ".xlsx": _rows_xlsx, ".xlsm": _rows_xlsx,
    ".docx": _rows_docx,
    ".pdf": _rows_pdf,
}

